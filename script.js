/* TRANSFORMA O NOME DO PRODUTO NO NOME DA FOTO */

function nomeDaImagem(nome) {
    return nome
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "");
}


/* RECURSO "AVISE-ME" */

function avisarDisponibilidade(produtoNome, variacaoNome) {
    const mensagem = `Olá! Gostaria de ser avisada quando o produto *${produtoNome}* na cor *${variacaoNome}* estiver disponível novamente.`;
    window.open(`https://wa.me/${numeroWhatsApp}?text=${encodeURIComponent(mensagem)}`, "_blank");
}


/* FUNÇÃO PARA TROCAR A FOTO AO CLICAR NA MINIATURA */

function trocarFotoModal(elThumb, novaSrc) {
    const imgDestaque = document.getElementById("imgDestaqueModal");
    if (imgDestaque) {
        imgDestaque.src = novaSrc;
    }
    document.querySelectorAll(".thumb-modal").forEach(t => t.style.borderColor = "#eee");
    if (elThumb) {
        elThumb.style.borderColor = "#111";
    }
}



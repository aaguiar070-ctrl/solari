/* TRANSFORMA O NOME DO PRODUTO NO NOME DA FOTO */

function nomeDaImagem(nome) {
    return nome
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "");
}


/* RECURSO "AVISE-ME" */

function avisarDisponibilidade(produtoNome, variacaoNome) {
    const mensagem = `Olá! Gostaria de ser avisada quando o produto *${produtoNome}* na cor *${variacaoNome}* estiver disponível novamente.`;
    window.open(`https://wa.me/${numeroWhatsApp}?text=${encodeURIComponent(mensagem)}`, "_blank");
}


/* ABRE OS DETALHES DO PRODUTO COM O SELETOR DE VARIANTES */

function abrirDetalhes(produto) {

    const nomeArquivo = nomeDaImagem(produto.nome);
    const imagemPrincipal = `images/${nomeArquivo}.jpeg`;
    const imagemSecundaria = `images/${nomeArquivo}-2.jpeg`;

    // Seleciona a lista de cores automaticamente
    let listaVariacoes = produto.variacoes;

    if (!listaVariacoes) {
        const nomeUpper = produto.nome.toUpperCase();
        const colecaoUpper = (produto.colecao || "").toUpperCase();

        if (nomeUpper.includes("SILVER") || colecaoUpper.includes("SILVER")) {
            listaVariacoes = variacoesSilver;
        } else {
            listaVariacoes = variacoesDourado;
        }
    }

    const janela = document.createElement("div");
    janela.className = "product-modal";

    let htmlVariacoes = "";
    if (!produto.esgotado) {
        htmlVariacoes = `<div class="variacoes-container">`;
        
        listaVariacoes.forEach((v) => {
            htmlVariacoes += `
                <div class="variacao-row" data-nome="${v.nome}">
                    <div class="variacao-swatch" style="background-color: ${v.cor || '#eee'};">
                        ${v.imagem ? `<img src="${v.imagem}" style="width:100%; height:100%; object-fit:cover;">` : ''}
                    </div>

                    <div class="variacao-details">
                        <span class="variacao-label">${v.nome}</span>
                        
                        ${v.esgotado ? `
                            <a href="#" class="btn-avise-me" data-variacao="${v.nome}">Avise-me</a>
                        ` : `
                            <div class="qty-box">
                                <span class="qty-val">0</span>
                                <div class="qty-controls">
                                    <button type="button" class="qty-btn btn-minus">-</button>
                                    <button type="button" class="qty-btn btn-plus">+</button>
                                </div>
                            </div>
                        `}
                    </div>
                </div>
            `;
        });

        htmlVariacoes += `</div>`;
    }

    janela.innerHTML = `
        <div class="modal-content">
            <button class="close-modal">&times;</button>

            <h2>${produto.nome}</h2>

            <div class="modal-images">
                <img src="${imagemPrincipal}" alt="${produto.nome}" onerror="this.style.display='none'">
                <img src="${imagemSecundaria}" alt="${produto.nome}" onerror="this.style.display='none'">
            </div>

            <p style="margin-bottom: 10px; color: #666;">Coleção: ${produto.colecao}</p>

            ${produto.promocao ? `
                <div class="old-price">R$ ${produto.precoAntigo}</div>
                <div class="price promotion-price">R$ ${produto.preco}</div>
            ` : `
                <div class="price">R$ ${produto.preco}</div>
            `}

            ${produto.esgotado ? `
                <strong class="sold-out">ESGOTADO</strong>
            ` : `
                ${htmlVariacoes}
                <button class="btn btn-comprar-whatsapp" style="width: 100%; margin-top: 15px;">
                    Comprar pelo WhatsApp
                </button>
            `}
        </div>
    `;

    document.body.appendChild(janela);

    // Lógica dos botões + e -
    janela.querySelectorAll(".variacao-row").forEach(linha => {
        const btnPlus = linha.querySelector(".btn-plus");
        const btnMinus = linha.querySelector(".btn-minus");
        const qtyVal = linha.querySelector(".qty-val");

        if (btnPlus && btnMinus && qtyVal) {
            btnPlus.addEventListener("click", () => {
                let atual = parseInt(qtyVal.textContent);
                qtyVal.textContent = atual + 1;
            });

            btnMinus.addEventListener("click", () => {
                let atual = parseInt(qtyVal.textContent);
                if (atual > 0) {
                    qtyVal.textContent = atual - 1;
                }
            });
        }
    });

    // Lógica dos links Avise-me
    janela.querySelectorAll(".btn-avise-me").forEach(btn => {
        btn.addEventListener("click", (e) => {
            e.preventDefault();
            const varNome = btn.getAttribute("data-variacao");
            avisarDisponibilidade(produto.nome, varNome);
        });
    });

    // Enviar pedido para o WhatsApp
    const btnComprar = janela.querySelector(".btn-comprar-whatsapp");
    if (btnComprar) {
        btnComprar.addEventListener("click", () => {
            let itensSelecionados = [];

            janela.querySelectorAll(".variacao-row").forEach(linha => {
                const varNome = linha.getAttribute("data-nome");
                const qtyVal = linha.querySelector(".qty-val");

                if (qtyVal) {
                    const qtd = parseInt(qtyVal.textContent);
                    if (qtd > 0) {
                        itensSelecionados.push(`${qtd}x ${varNome}`);
                    }
                }
            });

            let textoMensagem = "";
            if (itensSelecionados.length > 0) {
                textoMensagem = `Olá! Gostaria de comprar *${produto.nome}* (R$ ${produto.preco} cada):\n- ` + itensSelecionados.join("\n- ");
            } else {
                textoMensagem = `Olá! Gostaria de saber mais sobre o produto *${produto.nome}* no valor de R$ ${produto.preco}.`;
            }

            const urlWhatsApp = `https://wa.me/${numeroWhatsApp}?text=${encodeURIComponent(textoMensagem)}`;
            window.open(urlWhatsApp, "_blank");
        });
    }

    // Fechar Modal
    janela.querySelector(".close-modal").addEventListener("click", function() {
        janela.remove();
    });

    janela.addEventListener("click", function(e) {
        if (e.target === janela) {
            janela.remove();
        }
    });
}


/* CRIA O CARD DO PRODUTO */

function criarCard(produto) {

    const nomeArquivo = nomeDaImagem(produto.nome);
    const imagem = `images/${nomeArquivo}.jpeg`;

    const card = document.createElement("article");
    card.className = "card";

    card.innerHTML = `
        <div class="photo">
            ${produto.promocao ? `<span class="promotion-badge">PROMOÇÃO</span>` : ""}
            <img
                src="${imagem}"
                alt="${produto.nome}"
                onerror="this.style.display='none'; this.parentElement.innerHTML='ESPAÇO PARA FOTO';"
            >
        </div>

        <div class="info">
            <h4>${produto.nome}</h4>

            ${produto.promocao ? `
                <div class="old-price">R$ ${produto.precoAntigo}</div>
                <div class="price promotion-price">R$ ${produto.preco}</div>
            ` : `
                <div class="price">R$ ${produto.preco}</div>
            `}

            ${produto.esgotado ? `
                <span class="sold-out">ESGOTADO</span>
            ` : `
                <button class="btn details-btn">Ver detalhes</button>
            `}
        </div>
    `;

    if (!produto.esgotado) {
        card.querySelector(".details-btn").addEventListener("click", function() {
            abrirDetalhes(produto);
        });
    }

    return card;
}


/* MOSTRA OS PRODUTOS DA CATEGORIA */

function mostrarProdutos(tipo) {
    if (!areaProdutos) return;
    areaProdutos.innerHTML = "";

    const produtosFiltrados = produtos
        .filter(function(produto) {
            return produto.tipo === tipo;
        })
        .sort(function(a, b) {
            return a.esgotado - b.esgotado;
        });

    const titulo = document.createElement("h3");
    titulo.textContent = tipo;
    areaProdutos.appendChild(titulo);

    const grade = document.createElement("div");
    grade.className = "products";

    produtosFiltrados.forEach(function(produto) {
        grade.appendChild(criarCard(produto));
    });

    areaProdutos.appendChild(grade);
}


/* MOSTRA AS NOVIDADES */

function mostrarNovidades() {
    if (!areaNovidades) return;
    areaNovidades.innerHTML = "";

    const produtosNovidade = produtos
        .filter(function(produto) {
            return produto.novidade === true;
        })
        .sort(function(a, b) {
            return a.esgotado - b.esgotado;
        });

    const grade = document.createElement("div");
    grade.className = "products";

    produtosNovidade.forEach(function(produto) {
        grade.appendChild(criarCard(produto));
    });

    areaNovidades.appendChild(grade);
}


/* BOTÕES DAS CATEGORIAS */

botoesColecao.forEach(function(botao) {
    botao.addEventListener("click", function() {
        botoesColecao.forEach(function(outroBotao) {
            outroBotao.classList.remove("active");
        });

        botao.classList.add("active");

        const tipo = botao.getAttribute("data-collection");
        mostrarProdutos(tipo);
    });
});


/* INICIALIZAÇÃO */

mostrarNovidades();
mostrarProdutos("Colares");

if (botoesColecao.length > 0) {
    botoesColecao[0].classList.add("active");
}



/* TRANSFORMA O NOME DO PRODUTO NO NOME DA FOTO */

function nomeDaImagem(nome) {

    return nome
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "");

}


/* ABRE OS DETALHES DO PRODUTO */

function abrirDetalhes(produto) {

    const nomeArquivo =
        nomeDaImagem(produto.nome);

    const imagemPrincipal =
        `images/${nomeArquivo}.jpeg`;

    const imagemSecundaria =
        `images/${nomeArquivo}-2.jpeg`;

    const mensagem =
        encodeURIComponent(
            `Olá! Gostaria de comprar ${produto.nome}, no valor de R$ ${produto.preco}.`
        );


    const janela =
        document.createElement("div");

    janela.className =
        "product-modal";


    janela.innerHTML = `

        <div class="modal-content">

            <button class="close-modal">
                ×
            </button>

            <h2>
                ${produto.nome}
            </h2>

            <div class="modal-images">

                <img
                    src="${imagemPrincipal}"
                    alt="${produto.nome}"
                    onerror="this.style.display='none'"
                >

                <img
                    src="${imagemSecundaria}"
                    alt="${produto.nome}"
                    onerror="this.style.display='none'"
                >

            </div>

            <p>
                Coleção: ${produto.colecao}
            </p>

            ${
                produto.promocao
                ?
                `
                <div class="old-price">
                    R$ ${produto.precoAntigo}
                </div>

                <div class="price promotion-price">
                    R$ ${produto.preco}
                </div>
                `
                :
                `
                <div class="price">
                    R$ ${produto.preco}
                </div>
                `
            }

            ${
                produto.esgotado
                ?
                `<strong class="sold-out">
                    ESGOTADO
                </strong>`
                :
                `<a
                    class="btn"
                    href="https://wa.me/${numeroWhatsApp}?text=${mensagem}"
                    target="_blank">

                    Comprar pelo WhatsApp

                </a>`
            }

        </div>

    `;


    document.body.appendChild(janela);


    janela
        .querySelector(".close-modal")
        .addEventListener("click", function() {

            janela.remove();

        });

}


/* CRIA O CARD DO PRODUTO */

function criarCard(produto) {

    const nomeArquivo =
        nomeDaImagem(produto.nome);

    const imagem =
        `images/${nomeArquivo}.jpeg`;


    const card =
        document.createElement("article");

    card.className =
        "card";


    card.innerHTML = `

        <div class="photo">

            ${
                produto.promocao
                ?
                `<span class="promotion-badge">
                    PROMOÇÃO
                </span>`
                :
                ""
            }

            <img
                src="${imagem}"
                alt="${produto.nome}"
                onerror="this.style.display='none'; this.parentElement.innerHTML='ESPAÇO PARA FOTO';"
            >

        </div>

        <div class="info">

            <h4>
                ${produto.nome}
            </h4>

            ${
                produto.promocao
                ?
                `
                <div class="old-price">
                    R$ ${produto.precoAntigo}
                </div>

                <div class="price promotion-price">
                    R$ ${produto.preco}
                </div>
                `
                :
                `
                <div class="price">
                    R$ ${produto.preco}
                </div>
                `
            }

            ${
                produto.esgotado
                ?
                `<span class="sold-out">
                    ESGOTADO
                </span>`
                :
                `<button class="btn details-btn">
                    Ver detalhes
                </button>`
            }

        </div>

    `;


    if (!produto.esgotado) {

        card
            .querySelector(".details-btn")
            .addEventListener("click", function() {

                abrirDetalhes(produto);

            });

    }


    return card;

}


/* MOSTRA OS PRODUTOS DA CATEGORIA */

function mostrarProdutos(tipo) {

    areaProdutos.innerHTML = "";


    const produtosFiltrados =
        produtos
            .filter(function(produto) {

                return produto.tipo === tipo;

            })
            .sort(function(a, b) {

                return a.esgotado - b.esgotado;

            });


    const titulo =
        document.createElement("h3");

    titulo.textContent =
        tipo;

    areaProdutos.appendChild(titulo);


    const grade =
        document.createElement("div");

    grade.className =
        "products";


    produtosFiltrados.forEach(function(produto) {

        grade.appendChild(
            criarCard(produto)
        );

    });


    areaProdutos.appendChild(grade);

}


/* MOSTRA AS PROMOÇÕES */

function mostrarPromocoes() {

    if (!areaPromocoes) {
        return;
    }


    areaPromocoes.innerHTML = "";


    const produtosPromocao =
        produtos
            .filter(function(produto) {

                return produto.promocao === true;

            })
            .sort(function(a, b) {

                return a.esgotado - b.esgotado;

            });


    const grade =
        document.createElement("div");

    grade.className =
        "products";


    produtosPromocao.forEach(function(produto) {

        grade.appendChild(
            criarCard(produto)
        );

    });


    areaPromocoes.appendChild(grade);

}


/* BOTÕES DAS CATEGORIAS */

botoesColecao.forEach(function(botao) {

    botao.addEventListener("click", function() {

        botoesColecao.forEach(function(outroBotao) {

            outroBotao.classList.remove("active");

        });


        botao.classList.add("active");


        const tipo =
            botao.getAttribute("data-collection");


        mostrarProdutos(tipo);

    });

});


